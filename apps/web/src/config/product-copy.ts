export const CARE_LINE =
  'Прати при 40°C · Не відбілювати · Сушити в сушильній машині на делікатному '
  + 'режимі · Прасувати при середній температурі · Не піддавати хімчистці.';

export const CARE_WARNING = 'УВАГА! Вказано догляд за виробом без принтів!';

/** Гривні з копійок, без дробової частини: пороги в нас завжди круглі. */
function uah(minorAmount: number): string {
  return `${Math.round(minorAmount / 100).toLocaleString('uk-UA')}₴`;
}

export interface CopySettings {
  readonly returnDays: number;
  readonly freeShippingFromMinor: number;
}

/**
 * Дрібні рядки під кнопкою купівлі.
 *
 * Три речі, які людина питає рівно перед тим, як натиснути: чи спишуть
 * гроші зараз, чи можна повернути, скільки коштує доставка. Відповіді
 * стоять тут, а не в розділах нижче, бо до розділів долистує меншість.
 */
export function buyNotes(site: CopySettings, printed: boolean): readonly string[] {
  return [
    'Оплата не зараз — спершу підтвердимо наявність і напишемо',
    printed
      ? 'Річ із принтом виготовляємо під тебе — обмін лише за браку'
      : `Обмін/повернення базового одягу без принтів — ${site.returnDays} днів, `
        + 'якщо річ не носили та збережено товарний вигляд',
    `Доставка Новою Поштою, від ${uah(site.freeShippingFromMinor)} — за наш рахунок`,
  ];
}

/** Розділ «Строки й доставка». */
export function shippingText(site: CopySettings): readonly string[] {
  return [
    'Отримавши твоє замовлення, ми звіряємо наявність на складі постачальника '
    + 'у найближчий робочий час (Пн–Пт з 9.00 до 18.00). Повідомляємо тобі '
    + 'конкретну дату відправки замовлення і, отримавши твій ОК, надсилаємо '
    + 'рахунок на оплату.',
    'Доставку здійснюємо Новою Поштою — на відділення, в поштомат або курʼєром '
    + `за рахунок отримувача. Від ${uah(site.freeShippingFromMinor)} доставка за `
    + 'наш рахунок. Ми завжди ставимо фактичну оголошену цінність посилки.',
  ];
}

/**
 * Розділ «Оплата, обмін і повернення».
 *
 * Для речі з принтом додається третій абзац. Не тому, що закон для неї
 * інший, — а тому, що вона підпадає під виняток для товару, виготовленого
 * на замовлення, і сказати про це треба ДО оплати, а не у відповідь на
 * запит про повернення.
 */
export function paymentText(site: CopySettings, printed: boolean): readonly string[] {
  return [
    'Отримавши твій ОК по строках відправки, ми надішлемо рахунок на оплату. '
    + 'Всі платежі здійснюються за допомогою сервісів Monobank.',
    'Будь-які базові вироби без принтів підлягають обміну та поверненню '
    + 'відповідно до Закону України «Про захист прав споживачів». Щось не '
    + `підійшло — маєш ${site.returnDays} днів на повернення/обмін, якщо охайно `
    + 'приміряв, не носив і зберіг товарний вигляд.',
    ...(printed ? [
      'Річ із принтом ми виготовляємо під конкретне замовлення — виріб, розмір, '
      + 'колір і принт, — і не тримаємо на складі. Обміняти її нема на що, тож '
      + 'обмін і повернення тут лише за браку або нашої помилки: тоді міняємо '
      + 'або повертаємо гроші, зворотна пересилка за наш рахунок.',
    ] : []),
  ];
}
