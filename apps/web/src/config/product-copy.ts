/**
 * Тексти картки товару — одним файлом на обидві картки.
 *
 * Картки дві: базова річ (`GarmentOfferView`) і річ із принтом
 * (`PrintOfferView`). Строки, оплата, доставка й повернення в них однакові,
 * бо це той самий магазин, — але доти, доки живуть у двох файлах, вони
 * однакові лише до наступної правки. Так уже було з умовами повернення:
 * одне речення розійшлося в чотирьох місцях, і кожна копія обіцяла трохи
 * інше. Текст про гроші й строки — це те, що нам покажуть, коли дійде до
 * суперечки, тож він має бути один.
 *
 * Числа сюди НЕ вписані: строк повернення й поріг безкоштовної доставки
 * живуть у налаштуваннях (`/admin/nalashtuvannya`) і міняються без деплою.
 * Тому це функції від налаштувань, а не константи.
 */

