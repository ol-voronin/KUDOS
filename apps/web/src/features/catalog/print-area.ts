import type { PrintSizeTier } from '@dt/contracts';
import { GENERATED_AREAS } from './print-area.generated';

/**
 * Зона друку на фото виробу — серце авто-мокапів.
 *
 * Ідея: мокапи на кожну пару принт×колір ніхто не малює руками. Фото
 * виробу знімаються В ОДНОМУ ракурсі на всі кольори, тож зону друку
 * достатньо описати один раз НА ВИРІБ — і будь-який макет лягає на
 * будь-який колір сам. Змінюється колір → підміняється фото-підкладка,
 * принт лишається на місці.
 *
 * Числа — частки від ширини/висоти кадру (0..1), виміряні по чинних фото
 * з `public/garments/`. Якщо колись фото перезнімуть в іншому ракурсі —
 * підкрутити треба лише цю таблицю, більше ніде нічого.
 *
 *   x, y — лівий верхній кут зони друку;
 *   w    — ширина зони (максимальна, для MAXI-принтів).
 *
 * Висота не задається: макет зберігає власні пропорції від ширини.
 */
export interface PrintArea {
  readonly x: number;
  readonly y: number;
  readonly w: number;
}

/**
 * Таблиця більше не пишеться руками — її рахує `tools/gen-print-areas.py`.
 *
 * Руками було так: хтось один раз подивився на фото, прикинув частки й
 * записав. Далі фото перезняли, кадри роз'їхалися (у худі файли гуляють від
 * 343 до 356 px, а лінія плечей — на 3% висоти), числа лишились ті самі —
 * і принт поїхав. Найгірше, що поїхав по-різному на кожному виробі, тож на
 * вітрині сім речей виглядали як сім різних рішень.
 *
 * Тепер зона виводиться з самого силуету: фон рівний, виріб темніший, поріг
 * їх розділяє. Опорні точки — лінія плечей (перший рядок, де ширина
 * перевалює за 55% від найбільшої: у худі це плечі ПІД капюшоном) і ширина
 * по плечах. Саме по плечах, а не по корпусу: будь-який замір нижче
 * захоплює рукави, і в світшота «корпус» виходить на третину ширший, ніж у
 * футболки, хоча тіло під ними одне.
 *
 * Друк: ширина 60% плечей, верх — на 15% висоти корпусу нижче плечей. У худі
 * додаткові 6%, бо згори капюшон і шнурки.
 *
 * Перерахувати після перезнімання фото:
 *   python3 tools/gen-print-areas.py 0.60 0.15
 */
const DEFAULT_AREA: PrintArea = { x: 0.34, y: 0.25, w: 0.31 };

export function printAreaFor(garmentSlug: string): PrintArea {
  return GENERATED_AREAS[garmentSlug] ?? DEFAULT_AREA;
}

/**
 * Частка зони, яку займає принт свого розміру. Ті самі пропорції, що в
 * цінових ярусах: MAXI заповнює зону, MINI — нагрудний значок.
 */
const TIER_SCALE: Readonly<Record<PrintSizeTier, number>> = {
  MINI: 0.55,
  MEDIUM: 0.8,
  MAXI: 1,
};

export function tierScale(tier: PrintSizeTier): number {
  return TIER_SCALE[tier];
}
