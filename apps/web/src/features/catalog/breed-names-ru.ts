/** «Футболка с мопсом — …» або порожній рядок, якщо породи немає в словнику. */
export function breedRuSnippet(slug: string): string {
  const ru = BREED_RU_INSTRUMENTAL[slug];
  return ru === undefined ? '' : `Футболка с ${ru} — принт породы на футболке и худи.`;
}
