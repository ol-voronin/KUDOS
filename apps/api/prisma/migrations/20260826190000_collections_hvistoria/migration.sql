-- 2. На чому друкуємо: футболка, оверсайз, світшот, худі — тобто весь
--    асортимент. Список будується запитом, а не переліком slug'ів: вироби
--    заводяться сідом і можуть додаватися, а правило «друкуємо на всьому»
--    від цього не змінюється. Перелічений вручну slug розійшовся б із
--    базою на першому ж новому виробі.
INSERT INTO "PrintGarmentRule" ("id", "collectionId", "garmentId")
SELECT gen_random_uuid(), c."id", g."id"
FROM "Collection" c
CROSS JOIN "Garment" g
WHERE c."slug" IN ('mystetstvo', 'bos-dzvonyt', 'call-of-woof')
  AND g."type" IN ('TSHIRT', 'SWEATSHIRT', 'HOODIE')
ON CONFLICT ("collectionId", "garmentId") DO NOTHING;

-- 3. Старі жанри-розвідки — з публікації. Якщо в них уже є принти, вони
--    лишаються в базі й доступні за прямим посиланням; з вітрини зникають.
UPDATE "Collection"
SET "isPublished" = FALSE, "updatedAt" = CURRENT_TIMESTAMP
