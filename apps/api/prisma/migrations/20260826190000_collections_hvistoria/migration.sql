-- Чому міграцією, а не руками в адмінці: модуля «Колекції» в адмінці немає,
-- він у переліку майбутніх. А колекція — не ярлик для групування: саме вона
-- через `PrintGarmentRule` вирішує, на яких виробах узагалі можна друкувати
-- принт, а отже і його ціну. Принт без колекції показує на картці «ціну
-- уточнюємо» — тобто товар, який неможливо купити.
