-- Кошик, доставка й стан «замовлення прийняте, але ще не оплачене».
--
-- ── Чому зʼявився статус NEW ──────────────────────────────────────────
-- Досі замовлення народжувалося вже з рахунком: людина тиснула «Оплатити» і
-- одразу їхала на сторінку Monobank, тому першим станом і був
-- PENDING_PAYMENT. Тепер між «замовив» і «платить» стоїть людина — ми
-- звіряємо наявність, пишемо покупцеві й лише потім виставляємо рахунок.
--
-- Це не примха інтерфейсу: власне виробництво гарантує рівно один колір на
-- складі, і продати те, чого немає, дорожче, ніж зачекати годину.
--
-- ── Чому доставка полями, а не текстом у примітці ─────────────────────
-- «Напишіть у примітці, куди везти» означає, що адреса зберігається в тому
-- ж полі, що й «зробіть довжину коротше», і кожне відправлення починається
-- з читання чужого абзацу. Місто й відділення — окремі колонки, бо їх
-- переносять у накладну.
--
-- Довідника Нової Пошти тут немає навмисно: це вільний текст. Інтеграція з
-- їхнім API — окрема робота (ключ, ліміти, кеш довідника), а приймати
-- замовлення треба вже зараз. Коли інтеграція зʼявиться, ці ж колонки
-- почнуть заповнюватися вибором зі списку, і міграція даних не знадобиться.

ALTER TYPE "OrderStatus" ADD VALUE IF NOT EXISTS 'NEW' BEFORE 'PENDING_PAYMENT';

-- Міграцію можна прогнати двічі й нічого не зламати. Prisma сама цього не
-- зробить (вона веде журнал), але міграцію інколи докочують руками після
-- обірваного деплою, і падіння на другому проході в такий момент — це
-- півгодини гадання замість двох секунд.
DO $$
BEGIN
  CREATE TYPE "DeliveryMethod" AS ENUM ('NP_BRANCH', 'NP_POSTOMAT', 'NP_COURIER', 'PICKUP');
EXCEPTION
  WHEN duplicate_object THEN NULL;
END $$;

ALTER TABLE "Order"
  ADD COLUMN IF NOT EXISTS "deliveryMethod"  "DeliveryMethod" NOT NULL DEFAULT 'NP_BRANCH',
  ADD COLUMN IF NOT EXISTS "deliveryCity"    TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS "deliveryBranch"  TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS "recipientName"   TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS "recipientPhone"  TEXT NOT NULL DEFAULT '';

