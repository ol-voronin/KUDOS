-- Назва бренду: «Хвісторія».
--
-- Ім'я вирішувалося довше за все інше в цьому проєкті, і поки його не було,
-- не було ні домену, ні сенсу вмикати індексацію. Тепер воно є.
--
-- Чому міграцією, а не тільки полем в адмінці: адмінка міняє значення в
-- базі, яка вже працює, а міграція задає те, з чим підніметься наступна —
-- локальна копія, тестова, друга точка. Розійшовшись одного разу, вони
-- розходяться назавжди.
--
-- `Site.name` — внутрішня назва (заголовок у переліку сайтів);
-- `SiteSettings.brand` — те, що бачить покупець у шапці, футері й тайтлах.
-- Обидва йдуть разом, інакше в адмінці лишиться старе ім'я на видноті.
UPDATE "Site"
SET "name" = 'Хвісторія'
WHERE "key" = 'primary' AND "name" = 'Kudos print';

UPDATE "SiteSettings"
SET "brand" = 'Хвісторія'
WHERE "brand" = 'Kudos print';
