-- Меню шапки й тони головної.
--
-- ── 1. Меню ───────────────────────────────────────────────────────────
-- Було шість пунктів, з яких перші чотири («Каталог», «Вироби», «Колекції»,
-- «Свій принт») малювалися в шапці, а «Статті» й «Співпраця» існували лише
-- в мобільній шухляді. Тобто половина меню на широкому екрані була невидима,
-- і порядок пунктів вирішував, що саме зникне.
--
-- Стало чотири, і всі чотири видно завжди:
--   Породи    — питання №1, з яким приходять;
--   Колекції  — другий спосіб шукати те саме;
--   Вироби    — «а на чому це друкується»;
--   Свій принт — вхід для тих, чиєї породи немає.
--
-- «Статті» й «Співпраця» лишаються у футері: туди ходять із наміром, а не
-- випадково, і в шапці вони займали місце найпотрібніших пунктів.
--
-- ── 2. Тони головної ──────────────────────────────────────────────────
-- Кольорові підкладки секцій (бірюза, пісок, слива) прибираються. Причина не
-- в смаку: колір на цій сторінці має приносити фотографія товару, і коли його
-- приносить ще й фон секції, вони сперечаються — програє завжди товар.
--
-- Лишається ритм із трьох станів: білий за замовчуванням, кремовий — щоб
-- розділити зони, і РІВНО ОДНА чорна секція («Намалюємо саме вашого пса»)
-- там, де прокрутку треба зупинити.
--
-- ── 3. «Три способи отримати свій принт» ──────────────────────────────
-- Блок отримує іконки. Не номери: номер означає послідовність, а це три
-- ВАРІАНТИ, з яких обирають один — нумерація підказувала б, що перший
-- «правильніший».
--
-- Блок переписується цілком, але тільки якщо заголовок ще той самий, який
-- поставив сідер. Якщо його вже правили в адмінці — не чіпаємо: чужий текст
-- дорожчий за наші іконки.

-- 1 ─────────────────────────────────────────────────────────────────────
DELETE FROM "MenuItem" WHERE "area" = 'HEADER';

INSERT INTO "MenuItem" ("id", "siteId", "area", "group", "label", "href", "position", "updatedAt")
SELECT gen_random_uuid(), s."id", 'HEADER', '', v.label, v.href, v.position, now()
FROM "Site" s
CROSS JOIN (VALUES
  ('Породи',     '/breeds',       10),
  ('Колекції',   '/collections',  20),
  ('Вироби',     '/vyroby',       30),
  ('Свій принт', '/svoya-ideya',  40)
) AS v(label, href, position);

-- 2 ─────────────────────────────────────────────────────────────────────
-- Оновлюємо і чернетку, і опубліковану версію: інакше після наступного
-- «Зберегти» в адмінці кольори повернулися б із чернетки.
UPDATE "PageVersion" v
SET "blocks" = sub.blocks
FROM (
  SELECT
    v2."id" AS vid,
    jsonb_agg(
      CASE
        WHEN m.tone IS NULL THEN t.b
        ELSE jsonb_set(t.b, '{tone}', to_jsonb(m.tone))
      END
      ORDER BY t.ord
    ) AS blocks
  FROM "PageVersion" v2
  JOIN "Page" p ON p."id" = v2."pageId" AND p."slug" = 'home'
  CROSS JOIN LATERAL jsonb_array_elements(v2."blocks") WITH ORDINALITY AS t(b, ord)
  LEFT JOIN (VALUES
    ('породи',      'plain'),
    ('ready',       'plain'),
    ('collections', 'plain'),
    ('новинки',     'plain'),
    ('paths',       'cream'),
    ('custom',      'ink'),
    ('trust',       'cream'),
    ('b2b',         'cream'),
    ('faq',         'plain'),
    ('заявка',      'cream')
  ) AS m(bid, tone) ON m.bid = t.b->>'id'
  WHERE v2."status" IN ('DRAFT', 'PUBLISHED')
  GROUP BY v2."id"
) sub
WHERE v."id" = sub.vid;

-- 3 ─────────────────────────────────────────────────────────────────────
UPDATE "PageVersion" v
SET "blocks" = sub.blocks
FROM (
  SELECT
    v2."id" AS vid,
    jsonb_agg(
      CASE
        WHEN t.b->>'id' = 'paths'
         AND t.b->>'heading' = 'Три способи отримати свій принт'
        THEN t.b || jsonb_build_object(
          'lead', 'Обирайте той, що ближчий — ціни й строки різні.',
          'items', jsonb_build_array(
            jsonb_build_object(
              'icon', 'box',
              'title', 'Готовий принт',
              'text', '**від 1 190 ₴**, відправка за 1–2 дні, якщо є в наявності. Обираєте з каталогу виріб, колір і розмір — і оформлюєте одразу на сайті. [Дивитись каталог](#новинки)'
            ),
            jsonb_build_object(
              'icon', 'pencil',
              'title', 'Готовий принт + зміни',
              'text', '**від 1 190 ₴ + доплата**, зазвичай 2–4 дні на правки. Той самий принт, але з вашим текстом, кличкою або в іншому кольорі. [Написати нам](/zayavka)'
            ),
            jsonb_build_object(
              'icon', 'palette',
              'title', 'Принт з нуля',
              'text', '**Рахуємо після брифу**, від тижня — це проєкт, а не покупка. Малюємо саме вашого пса з фото: портрет, обкладинка, будь-яка ідея. Правки включені. [Заповнити бриф](/svoya-ideya)'
            )
          )
        )
        ELSE t.b
      END
      ORDER BY t.ord
    ) AS blocks
  FROM "PageVersion" v2
  JOIN "Page" p ON p."id" = v2."pageId" AND p."slug" = 'home'
  CROSS JOIN LATERAL jsonb_array_elements(v2."blocks") WITH ORDINALITY AS t(b, ord)
  WHERE v2."status" IN ('DRAFT', 'PUBLISHED')
  GROUP BY v2."id"
) sub
WHERE v."id" = sub.vid;
