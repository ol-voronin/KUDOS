-- «Ти» на сторінці «Свій принт із фото».
--
-- Головну на «ти» перевела попередня міграція; ця доводить до того самого
-- тону сторінку власної ідеї — другу за важливістю сторінку продажу.
-- Оферта, приватність і співпраця лишаються на «ви» свідомо: перші дві —
-- юридичні документи, третя звертається до юросіб.
--
-- Той самий прийом, що й для головної: оновлюємо і чернетку, і опубліковану
-- версію, блоки замінюємо значеннями з сіда — сід і база після міграції
-- кажуть одне й те саме слово в слово.

UPDATE "PageVersion" v
SET "blocks" = sub.blocks,
    "excerpt" = 'Намалюємо твою собаку з фотографії — портрет, обкладинка журналу, будь-який жанр. Друкуємо на футболці, худі або світшоті.',
    "seoTitle" = 'Принт із фото твоєї собаки — {{brand}}',
    "seoDescription" = 'Намалюємо твого пса з фотографії й надрукуємо на футболці, худі чи світшоті. Портрет, обкладинка журналу, будь-який жанр. {{city}}, доставка по Україні.'
FROM (
  SELECT
    v2."id" AS vid,
    jsonb_agg(
      CASE
        WHEN t.b->>'id' = 'hero' THEN '{"id": "hero", "type": "hero", "tone": "cream", "eyebrow": "Малюємо з твого фото", "heading": "Твій собака, а не **просто схожий**", "lead": "Готові принти — це породи. А тут буде саме твій пес: із його вухом, плямою й виразом морди. Надішли кілька фотографій — решту зробимо ми.", "footnote": "", "links": [{"label": "Розповісти про свого пса", "href": "/zayavka", "secondary": false}]}'::jsonb
        WHEN t.b->>'id' = 'how' THEN '{"id": "how", "type": "steps", "tone": "plain", "heading": "Як це працює", "lead": "", "items": [{"title": "Надсилаєш фото", "text": "Три-чотири кадри при денному світлі. Морда крупно й кілька в повний зріст."}, {"title": "Обираємо жанр", "text": "Портрет у стилі старих майстрів, обкладинка журналу, кіноплакат — або твоя ідея."}, {"title": "Малюємо й показуємо", "text": "Надсилаємо ескіз до друку. Правки на цьому етапі безкоштовні."}, {"title": "Друкуємо", "text": "Після твого «так» друкуємо на обраному виробі й відправляємо."}]}'::jsonb
        WHEN t.b->>'id' = 'promise' THEN '{"id": "promise", "type": "features", "tone": "cream", "heading": "Що ми обіцяємо", "items": [{"icon": "heart", "title": "Схожість", "text": "Якщо на ескізі не впізнаєш свого пса — переробляємо, не питаючи."}, {"icon": "scissors", "title": "Шиємо самі", "text": "Виріб і друк — одне виробництво {{cityIn}}, без посередників."}, {"icon": "shield", "title": "Твоє фото — твоє", "text": "Не публікуємо роботу без твого дозволу. Детальніше — у [політиці](/pryvatnist)."}]}'::jsonb
        WHEN t.b->>'id' = 'lead' THEN '{"id": "lead", "type": "leadForm", "tone": "plain", "heading": "Розкажи про свого пса", "text": "Кличка, порода й пара слів про характер — цього досить, щоб почати. Фото попросимо в Telegram.", "source": "/svoya-ideya"}'::jsonb
        ELSE t.b
      END
      ORDER BY t.ord
    ) AS blocks
  FROM "PageVersion" v2
  JOIN "Page" p ON p."id" = v2."pageId" AND p."slug" = 'svoya-ideya'
  CROSS JOIN LATERAL jsonb_array_elements(v2."blocks") WITH ORDINALITY AS t(b, ord)
  WHERE v2."status" IN ('DRAFT', 'PUBLISHED')
  GROUP BY v2."id"
) sub
WHERE v."id" = sub.vid;
