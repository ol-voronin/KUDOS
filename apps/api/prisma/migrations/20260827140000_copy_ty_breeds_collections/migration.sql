-- Копірайт на «ти», строки 4–7 днів, породи й колекції.
--
-- ── Що тут і чому саме міграцією ──────────────────────────────────────
--
-- Тексти сторінок лежать у базі, а сідер не чіпає сторінки, яких торкалася
-- людина. Тобто «оновіть сід» не змінить нічого на працюючому сайті.
--
-- ── Чому «ти» ─────────────────────────────────────────────────────────
--
-- Рішення замовника, і воно наскрізне: половина на «ти» читається як два
-- різні магазини. Виняток свідомий — блок для зоомагазинів і клінік: там
-- інша аудиторія й інша розмова, «ти» до юрособи звучить фамільярно.
--
-- ── Чому строк став підстановкою ──────────────────────────────────────
--
-- {{productionDays}} стоїть у трьох блоках головної, у картці товару й у
-- відповідях на питання. Зашитий числом, він розійшовся б із тим, що кажуть
-- у Telegram, — а саме з такої розбіжності виростає «мені обіцяли інше».
--
-- ── Чого тут НЕМАЄ ────────────────────────────────────────────────────
--
-- Перейменування ОПУБЛІКОВАНИХ колекцій. Перейменування змінює slug, тобто
-- ламає всі наявні посилання, а зіставити «Мистецтво бути шедевром» із
-- новим переліком я не можу вгадуванням. Перейменовані лише чернетки — на
-- них ніщо не посилається.

-- 1 ── строк виготовлення в налаштуваннях ──────────────────────────────
ALTER TABLE "SiteSettings"
  ADD COLUMN IF NOT EXISTS "productionDaysMin" INTEGER NOT NULL DEFAULT 4,
  ADD COLUMN IF NOT EXISTS "productionDaysMax" INTEGER NOT NULL DEFAULT 7;

ALTER TABLE "SiteSettings" DROP CONSTRAINT IF EXISTS "SiteSettings_production_sane";
ALTER TABLE "SiteSettings" ADD CONSTRAINT "SiteSettings_production_sane"
  CHECK ("productionDaysMin" >= 0 AND "productionDaysMax" >= "productionDaysMin" AND "productionDaysMax" <= 120);

