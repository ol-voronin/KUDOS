-- «Метис» прибираємо — але тільки якщо на ньому не висить жоден принт.
-- Видалити породу разом із привʼязками означало б тихо прибрати товар із
-- каталогу; якщо принти є, порода лишається, і це видно в адмінці.
DELETE FROM "Breed" b
WHERE b.slug = 'metys'
  AND NOT EXISTS (SELECT 1 FROM "PrintBreed" pb WHERE pb."breedId" = b.id)
  AND NOT EXISTS (SELECT 1 FROM "PageBreed" pg WHERE pg."breedId" = b.id);

