-- «Футболка оверсайз чоловіча» → «... унісекс».
-- Опис завжди казав, що вона пасує і жінкам; назва нарешті це визнала
-- (фотосесія вересня-2026 знята саме як унісекс — рішення Олексія).
-- Слаг НЕ чіпаємо: на ньому живуть посилання, фото в репо і кошики.
UPDATE "Garment"
SET "name" = 'Футболка оверсайз унісекс'
WHERE "slug" = 'futbolka-oversayz-cholovicha'
  AND "name" = 'Футболка оверсайз чоловіча';
